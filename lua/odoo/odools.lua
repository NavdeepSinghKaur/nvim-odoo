-- Generates the config of odoo-ls (Odoo's language server) from your settings, so paths are
-- written once (lua/odoo/local.lua). Result: stdpath("state")/odoo/odools.toml
-- Have your own odools.toml? Set  odools_config = "/path/to/odools.toml"  in local.lua.
local S = require("odoo.settings")
local P = require("odoo.paths")
local M = {}

local function q(s) return vim.json.encode(s) end -- TOML basic strings are JSON strings

function M.content()
  local addons = {}
  for _, d in ipairs(P.addon_dirs()) do
    if d ~= S.core_addons then table.insert(addons, "  " .. q(d) .. ",") end
  end
  local own = vim.tbl_map(function(d) return q(d .. "/**") end, S.own_addons)
  local lines = {
    "# Generated by nvim (lua/odoo/odools.lua) from lua/odoo/local.lua. Do not edit: rewritten on start.",
    "[[config]]",
    'name = "default"',
    "odoo_path = " .. q(S.core),
    "addons_paths = [",
  }
  vim.list_extend(lines, addons)
  table.insert(lines, "]")
  if S.python and S.python ~= "" then table.insert(lines, "python_path = " .. q(S.python)) end
  vim.list_extend(lines, {
    "# only report missing imports for Odoo modules (odoo.addons.x), not for every pip package",
    'diag_missing_imports = "only_odoo"',
    "",
    "# Report problems only for YOUR code (otherwise ~28 000 diagnostics about core while indexing)",
    "[[config.diagnostic_filters]]",
    "paths = [" .. table.concat(own, ", ") .. "]",
    'path_type = "notin"',
  })
  return lines
end

--- Path of the odools.toml to use (written if it changed).
function M.path()
  if S.odools_config then return S.odools_config end
  local dir = vim.fn.stdpath("state") .. "/odoo"
  local file = dir .. "/odools.toml"
  local lines = M.content()
  local old = vim.uv.fs_stat(file) and vim.fn.readfile(file) or {}
  if not vim.deep_equal(old, lines) then
    vim.fn.mkdir(dir, "p")
    vim.fn.writefile(lines, file)
  end
  return file
end

return M
